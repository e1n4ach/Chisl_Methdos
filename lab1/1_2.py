a = [0, 2, -7, 2, -7]          # поддиагональ
b = [-14, 7, -18, -13, -7]     # главная диагональ
c = [6, 0, -9, 2, 0]           # наддиагональ
d = [82, -51, -46, 111, 35]    # правая часть

solution = thomas_algorithm(a, b, c, d)

print("Решение системы:")
for i, xi in enumerate(solution, start=1):
    print(f"x{i} = {xi}")
