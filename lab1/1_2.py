def check_stability(a, b, c):
    """
    Проверка достаточных условий устойчивости метода прогонки.
    """

    n = len(b)

    # Проверка внутренних коэффициентов:
    # для внутренних строк под- и наддиагональные элементы должны быть ненулевыми
    for i in range(1, n - 1):
        if a[i] == 0:
            raise ValueError(
                f"Нарушено условие устойчивости: a[{i}] = 0 "
                f"(для внутренней строки поддиагональный элемент должен быть ненулевым)."
            )
        if c[i] == 0:
            raise ValueError(
                f"Нарушено условие устойчивости: c[{i}] = 0 "
                f"(для внутренней строки наддиагональный элемент должен быть ненулевым)."
            )

    # Проверка диагонального преобладания
    strict_found = False  # будет True, если хотя бы в одной строке неравенство строгое

    for i in range(n):
        if abs(b[i]) < abs(a[i]) + abs(c[i]):
            raise ValueError(
                f"Нарушено условие устойчивости в строке {i + 1}: "
                f"|b[{i}]| = {abs(b[i])} < |a[{i}]| + |c[{i}]| = {abs(a[i]) + abs(c[i])}"
            )

        if abs(b[i]) > abs(a[i]) + abs(c[i]):
            strict_found = True

    if not strict_found:
        raise ValueError(
            "Нарушено условие устойчивости: ни в одной строке нет строгого "
            "диагонального преобладания."
        )

def thomas_algorithm(a, b, c, d):
    """
    Метод прогонки для решения трёхдиагональной СЛАУ.

    a — поддиагональ
    b — главная диагональ
    c — наддиагональ
    d — правая часть
    """

    # Число уравнений
    n = len(d)

    # Прогоночные коэффициенты:
    # x[i] = P[i] * x[i+1] + Q[i]
    P = [0.0] * n
    Q = [0.0] * n

    # Начальные коэффициенты по первой строке
    P[0] = -c[0] / b[0]
    Q[0] = d[0] / b[0]

    # Прямой ход: вычисление P[i] и Q[i]
    for i in range(1, n):
        denominator = b[i] + a[i] * P[i - 1]

        # Проверка на деление на ноль
        if abs(denominator) < 1e-12:
            raise ValueError(f"Нулевой знаменатель на шаге {i}")

        # Для последней строки P[i] не нужен
        if i < n - 1:
            P[i] = -c[i] / denominator
        else:
            P[i] = 0.0

        Q[i] = (d[i] - a[i] * Q[i - 1]) / denominator

    # Обратный ход: восстановление решения
    x = [0.0] * n
    x[n - 1] = Q[n - 1]

    for i in range(n - 2, -1, -1):
        x[i] = P[i] * x[i + 1] + Q[i]

    return x


