def print_matrix(A, title):
    """
    Красивый вывод матрицы в консоль.

    Зачем нужна эта функция:
    - в отчёте и на защите удобно показать саму нормальную систему;
    - видно, из каких чисел она составилась после подсчёта сумм;
    - можно проверить, что мы действительно работаем по алгоритму МНК,
      а не просто подставили ответ.

    Параметры:
    A     -- двумерный массив NumPy, то есть матрица системы
    title -- заголовок перед матрицей
    """
    print(title)
    for row in A:
        print("  ", " ".join(f"{value:14.8f}" for value in row))
    print()



def print_vector(b, title):
    """
    Красивый вывод вектора правой части системы.

    Правая часть нормальной системы в МНК состоит из сумм вида:
    Σy, Σxy, Σx^2 y и т.д. в зависимости от степени многочлена.
    Эта функция нужна только для удобного и наглядного вывода.
    """
    print(title)
    for value in b:
        print(f"  {value:14.8f}")
    print()



def least_squares_linear(x, y):
    """
    Находит приближающий многочлен 1-й степени методом наименьших квадратов.

    Ищем многочлен вида:
        F1(x) = a0 + a1*x

    По методичке коэффициенты a0 и a1 находятся из нормальной системы:

        [N+1   Σx   ] [a0] = [Σy]
        [Σx   Σx^2 ] [a1]   [Σxy]

    Здесь N = len(x) - 1, потому что в методичке индексация идёт от 0 до N,
    то есть всего точек N + 1.

    Возвращаем:
    coeffs -- коэффициенты [a0, a1]
    f      -- значения F1(x_i) в исходных узлах
    phi    -- сумма квадратов ошибок Φ = Σ(F1(x_i) - y_i)^2
    A      -- матрица нормальной системы
    b      -- правая часть системы
    sums   -- словарь с промежуточными суммами для удобства вывода
    """

    # Количество узлов в обозначениях методички: i = 0..N.
    # Если точек 6, то N = 5.
    n = len(x) - 1

    # ------------------------------------------------------------------------
    # Считаем суммы, которые напрямую входят в нормальную систему.
    # Это ровно тот шаг, который в методичке делается перед составлением СЛАУ.
    # ------------------------------------------------------------------------
    sx = np.sum(x)           # Σx
    sx2 = np.sum(x ** 2)     # Σx^2
    sy = np.sum(y)           # Σy
    sxy = np.sum(x * y)      # Σxy

    # ------------------------------------------------------------------------
    # Собираем матрицу A и вектор b нормальной системы A * a = b.
    # После этого задача МНК сводится к решению обычной системы линейных
    # алгебраических уравнений относительно неизвестных коэффициентов a0, a1.
    # ------------------------------------------------------------------------
    A = np.array([
        [n + 1, sx],
        [sx, sx2]
    ], dtype=float)

    b = np.array([sy, sxy], dtype=float)

    # Решаем систему и получаем коэффициенты прямой,
    # которая лучше всего приближает данные в смысле МНК.
    coeffs = np.linalg.solve(A, b)
    a0, a1 = coeffs

    # Вычисляем значения найденного многочлена в исходных узлах x_i.
    # Это понадобится для подсчёта ошибок и вывода таблицы.
    f = a0 + a1 * x

    # Функционал МНК: сумма квадратов отклонений от табличных значений.
    # Чем меньше Φ, тем лучше приближение по критерию МНК.
    phi = np.sum((f - y) ** 2)

    sums = {
        'N': n,
        'sum_x': sx,
        'sum_x2': sx2,
        'sum_y': sy,
        'sum_xy': sxy,
    }

    return coeffs, f, phi, A, b, sums



def least_squares_quadratic(x, y):
    """
    Находит приближающий многочлен 2-й степени методом наименьших квадратов.

    Ищем многочлен вида:
        F2(x) = a0 + a1*x + a2*x^2

    По методичке коэффициенты a0, a1, a2 находятся из нормальной системы:

        [N+1   Σx    Σx^2 ] [a0] = [Σy    ]
        [Σx   Σx^2   Σx^3 ] [a1]   [Σxy   ]
        [Σx^2 Σx^3   Σx^4 ] [a2]   [Σx^2y ]

    Это уже система 3x3, потому что неизвестных коэффициентов три.
    """

    # Число N в обозначениях методички.
    n = len(x) - 1

    # ------------------------------------------------------------------------
    # Считаем все суммы, которые понадобятся для составления нормальной системы
    # второго порядка.
    # ------------------------------------------------------------------------
    sx = np.sum(x)                 # Σx
    sx2 = np.sum(x ** 2)           # Σx^2
    sx3 = np.sum(x ** 3)           # Σx^3
    sx4 = np.sum(x ** 4)           # Σx^4
    sy = np.sum(y)                 # Σy
    sxy = np.sum(x * y)            # Σxy
    sx2y = np.sum((x ** 2) * y)    # Σx^2 y

    # Матрица нормальной системы для квадратичного многочлена.
    A = np.array([
        [n + 1, sx, sx2],
        [sx, sx2, sx3],
        [sx2, sx3, sx4]
    ], dtype=float)

    # Правая часть системы.
    b = np.array([sy, sxy, sx2y], dtype=float)

    # Решаем систему и получаем коэффициенты a0, a1, a2.
    coeffs = np.linalg.solve(A, b)
    a0, a1, a2 = coeffs

    # Находим значения многочлена F2 в исходных точках таблицы.
    f = a0 + a1 * x + a2 * x ** 2

    # Сумма квадратов ошибок для многочлена 2-й степени.
    phi = np.sum((f - y) ** 2)

    sums = {
        'N': n,
        'sum_x': sx,
        'sum_x2': sx2,
        'sum_x3': sx3,
        'sum_x4': sx4,
        'sum_y': sy,
        'sum_xy': sxy,
        'sum_x2y': sx2y,
    }

    return coeffs, f, phi, A, b, sums



def main():
    """
    Основная функция программы.

    Здесь последовательно реализуются все шаги решения лабораторной работы:
    1. Задаются исходные табличные данные варианта.
    2. Строится МНК-многочлен 1-й степени.
    3. Строится МНК-многочлен 2-й степени.
    4. Для каждого считается сумма квадратов ошибок.
    5. Сравнивается качество приближения.
    6. Строится общий график.
    """

    # ------------------------------------------------------------------------
    # Исходные данные варианта 24 из файла задания.
    # x -- узлы таблицы
    # y -- значения функции в этих узлах
    # ------------------------------------------------------------------------
    x = np.array([0.1, 0.5, 0.9, 1.3, 1.7, 2.1], dtype=float)
    y = np.array([100.0, 4.0, 1.2346, 0.59172, 0.34602, 0.22676], dtype=float)

    print("ЛР 3.3, вариант 24")
    print("Метод: МНК через нормальные системы из методички")
    print()

    # Выводим исходную таблицу, чтобы было видно, с какими данными работаем.
    print("Исходные данные:")
    for i in range(len(x)):
        print(f"i = {i:>1d}; x[{i}] = {x[i]:8.5f}; y[{i}] = {y[i]:10.5f}")
    print()

    # ======================== МНОГОЧЛЕН 1-Й СТЕПЕНИ ========================
    # На этом шаге строится линейное приближение: F1(x) = a0 + a1*x.
    coeffs1, f1, phi1, A1, b1, sums1 = least_squares_linear(x, y)
    a0_1, a1_1 = coeffs1

    print("=" * 90)
    print("ПРИБЛИЖАЮЩИЙ МНОГОЧЛЕН 1-Й СТЕПЕНИ")
    print("F1(x) = a0 + a1*x")
    print()

    # Показываем все суммы, из которых составлена нормальная система.
    print("Суммы для нормальной системы:")
    print(f"N = {sums1['N']}")
    print(f"Σx    = {sums1['sum_x']:.8f}")
    print(f"Σx^2  = {sums1['sum_x2']:.8f}")
    print(f"Σy    = {sums1['sum_y']:.8f}")
    print(f"Σxy   = {sums1['sum_xy']:.8f}")
    print()

    # Выводим саму систему в матричной форме.
    print_matrix(A1, "Матрица нормальной системы для F1:")
    print_vector(b1, "Правая часть системы для F1:")

    # Печатаем найденные коэффициенты и сам итоговый многочлен.
    print("Решение системы:")
    print(f"a0 = {a0_1:.8f}")
    print(f"a1 = {a1_1:.8f}")
    print()
    print(f"Итоговый многочлен: F1(x) = {a0_1:.8f} + ({a1_1:.8f})*x")
    print()

    # Для каждой табличной точки считаем:
    # 1) значение приближающего многочлена F1(x_i)
    # 2) квадрат ошибки (F1(x_i) - y_i)^2
    # Это позволяет затем получить сумму квадратов ошибок Φ1.
    print("Таблица значений F1(x_i) и квадратов ошибок:")
    print(f"{'i':>2} {'x_i':>10} {'y_i':>12} {'F1(x_i)':>14} {'(F1-y)^2':>16}")
    for i in range(len(x)):
        err2 = (f1[i] - y[i]) ** 2
        print(f"{i:>2d} {x[i]:>10.5f} {y[i]:>12.5f} {f1[i]:>14.8f} {err2:>16.8f}")
    print()
    print(f"Сумма квадратов ошибок Φ1 = {phi1:.8f}")
    print()

    # ======================== МНОГОЧЛЕН 2-Й СТЕПЕНИ ========================
    # Теперь строим квадратичное приближение:
    # F2(x) = a0 + a1*x + a2*x^2.
    coeffs2, f2, phi2, A2, b2, sums2 = least_squares_quadratic(x, y)
    a0_2, a1_2, a2_2 = coeffs2

    print("=" * 90)
    print("ПРИБЛИЖАЮЩИЙ МНОГОЧЛЕН 2-Й СТЕПЕНИ")
    print("F2(x) = a0 + a1*x + a2*x^2")
    print()

    # Снова выводим все промежуточные суммы, но уже для системы 3x3.
    print("Суммы для нормальной системы:")
    print(f"Σx      = {sums2['sum_x']:.8f}")
    print(f"Σx^2    = {sums2['sum_x2']:.8f}")
    print(f"Σx^3    = {sums2['sum_x3']:.8f}")
    print(f"Σx^4    = {sums2['sum_x4']:.8f}")
    print(f"Σy      = {sums2['sum_y']:.8f}")
    print(f"Σxy     = {sums2['sum_xy']:.8f}")
    print(f"Σx^2*y  = {sums2['sum_x2y']:.8f}")
    print()

    print_matrix(A2, "Матрица нормальной системы для F2:")
    print_vector(b2, "Правая часть системы для F2:")

    # Печатаем коэффициенты квадратичного многочлена.
    print("Решение системы:")
    print(f"a0 = {a0_2:.8f}")
    print(f"a1 = {a1_2:.8f}")
    print(f"a2 = {a2_2:.8f}")
    print()
    print(f"Итоговый многочлен: F2(x) = {a0_2:.8f} + ({a1_2:.8f})*x + ({a2_2:.8f})*x^2")
    print()

    # Аналогично линейному случаю строим таблицу ошибок для F2.
    print("Таблица значений F2(x_i) и квадратов ошибок:")
    print(f"{'i':>2} {'x_i':>10} {'y_i':>12} {'F2(x_i)':>14} {'(F2-y)^2':>16}")
    for i in range(len(x)):
        err2 = (f2[i] - y[i]) ** 2
        print(f"{i:>2d} {x[i]:>10.5f} {y[i]:>12.5f} {f2[i]:>14.8f} {err2:>16.8f}")
    print()
    print(f"Сумма квадратов ошибок Φ2 = {phi2:.8f}")
    print()

    # ------------------------------------------------------------------------
    # Сравниваем два найденных приближения.
    # По критерию метода наименьших квадратов лучше тот многочлен,
    # у которого сумма квадратов ошибок меньше.
    # ------------------------------------------------------------------------
    print("=" * 90)
    if phi2 < phi1:
        print("Лучшее приближение по критерию МНК дает многочлен 2-й степени,")
        print("так как для него сумма квадратов ошибок меньше.")
    else:
        print("Лучшее приближение по критерию МНК дает многочлен 1-й степени,")
        print("так как для него сумма квадратов ошибок меньше.")
    print("=" * 90)

    # ============================== ГРАФИК ================================
    # Для красивого графика строим плотную сетку из 400 точек.
    # На ней считаем значения обоих многочленов.
    x_dense = np.linspace(np.min(x), np.max(x), 400)
    y1_dense = a0_1 + a1_1 * x_dense
    y2_dense = a0_2 + a1_2 * x_dense + a2_2 * x_dense ** 2

    # Создаём рисунок.
    plt.figure(figsize=(10, 6))

    # Исходные табличные данные показываем точками.
    plt.scatter(x, y, label='Табличные данные')

    # Линейное приближение рисуем линией.
    plt.plot(x_dense, y1_dense, label='МНК, 1-я степень')

    # Квадратичное приближение рисуем отдельной линией.
    plt.plot(x_dense, y2_dense, label='МНК, 2-я степень')

    # Оформление графика.
    plt.xlabel('x')
    plt.ylabel('y')
    plt.title('ЛР 3.3, вариант 24: МНК')
    plt.grid(True)
    plt.legend()
    plt.tight_layout()

    # Сохраняем график в файл, чтобы его можно было вставить в отчёт.
    plt.savefig('3_3.png', dpi=150)

    # Показываем график на экране.
    plt.show()


